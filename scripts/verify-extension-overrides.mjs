import { existsSync, readFileSync } from "node:fs";

let failed = false;

function fail(message) {
  console.error(`ERROR: ${message}`);
  failed = true;
}

for (const path of ["src/admin/KcPage.tsx", "src/account/KcPage.tsx"]) {
  if (!existsSync(path)) {
    fail(`${path} was not generated by Keycloakify`);
    continue;
  }

  const content = readFileSync(path, "utf8");

  if (content.includes("DPoP({") || content.includes('mode: "auto"')) {
    fail(`${path} still enables DPoP auto mode`);
  }

  if (content.includes("oidcEarlyInit") && !content.includes('sessionRestorationMethod: "full page redirect"')) {
    fail(`${path} does not force full-page session restoration`);
  }
}

const emailTemplate = "src/email/html/template.ftl";
if (!existsSync(emailTemplate)) {
  fail(`${emailTemplate} is missing`);
} else if (!readFileSync(emailTemplate, "utf8").includes("CoreLink")) {
  fail(`${emailTemplate} lost CoreLink branding`);
}

if (failed) {
  process.exit(1);
}

console.log("Generated Keycloakify extension bootstrap verified.");
